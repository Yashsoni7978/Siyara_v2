// Helper to get normalized industry categories with dynamic counts from actual data
export const getIndustryCategories = () => {
  const counts = { ALL: projectsData.length };
  
  projectsData.forEach((project) => {
    const ind = project.industry;
    counts[ind] = (counts[ind] || 0) + 1;
  });

  const categories = [
    { id: 'ALL', name: 'All', count: `${projectsData.length} Delivered Projects`, icon: 'Grid' },
    { id: 'Real Estate', name: 'Real Estate', count: `${counts['Real Estate'] || 0} Delivered Projects`, icon: 'Building' },
    { id: 'Healthcare', name: 'Healthcare', count: `${counts['Healthcare'] || 0} Delivered Projects`, icon: 'ShieldPlus' },
    { id: 'Hospitality', name: 'Hospitality', count: `${counts['Hospitality'] || 0} Delivered Projects`, icon: 'Hotel' },
    { id: 'Events', name: 'Events', count: `${counts['Events'] || 0} Delivered Projects`, icon: 'Ticket' },
    { id: 'Anchor / Emcee', name: 'Anchor / Emcee', count: `${counts['Anchor / Emcee'] || 0} Delivered Projects`, icon: 'Mic' },
    { id: 'Fashion', name: 'Fashion', count: `${counts['Fashion'] || 0} Delivered Projects`, icon: 'Shirt' },
    { id: 'E-Commerce', name: 'E-Commerce', count: `${counts['E-Commerce'] || 0} Delivered Projects`, icon: 'ShoppingBag' },
    { id: 'Architecture & Interiors', name: 'Architecture & Interiors', count: `${counts['Architecture & Interiors'] || 0} Delivered Projects`, icon: 'Compass' },
    { id: 'Food & Beverage', name: 'Food & Beverage', count: `${counts['Food & Beverage'] || 0} Delivered Projects`, icon: 'Coffee' },
    { id: 'AI / Automation', name: 'AI / Automation', count: `${counts['AI / Automation'] || 0} Delivered Projects`, icon: 'Cpu' },
    { id: 'Fintech', name: 'Fintech', count: `${counts['Fintech'] || 0} Delivered Projects`, icon: 'Wallet' }
  ];

  // Return only categories that have at least 1 delivered project
  return categories.filter(
    (cat) => cat.id === 'ALL' || (counts[cat.id] && counts[cat.id] > 0)
  );
};
